package main

import (
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/hashimthearab/rust-mcbe/core/javaedition/legacy"
)

// bedrockItem is one entry of minecraft-data's Bedrock item list.
type bedrockItem struct {
	ID             int             `json:"id"`
	Name           string          `json:"name"`
	ComponentBased bool            `json:"componentBased"`
	Version        string          `json:"version"`
	NBT            json.RawMessage `json:"nbt"`
}

// renamedItems maps flattened Java item names to the Bedrock item that replaced them.
var renamedItems = map[string]string{
	"cactus_green":     "green_dye",
	"dandelion_yellow": "yellow_dye",
	"rose_red":         "red_dye",
	"oak_door":         "wooden_door",
	"sign":             "oak_sign",
	"item_frame":       "frame",
	"map":              "empty_map",
	"furnace_minecart": "minecart",
}

// writeItems writes bedrock_items.json.gz, the target version's item registry, and items.tsv,
// the Java 1.7.10 item table.
func writeItems(read func(path string, into any) error) error {
	var registry []bedrockItem
	var flattening struct {
		Items map[string]string `json:"items"`
	}
	if err := read("data/bedrock/1.26.60/items.json", &registry); err != nil {
		return err
	}
	if err := read("data/pc/common/legacy.json", &flattening); err != nil {
		return err
	}
	sort.Slice(registry, func(i, j int) bool { return registry[i].ID < registry[j].ID })
	ids := make(map[string]int, len(registry))
	for _, item := range registry {
		ids[item.Name] = item.ID
	}
	if err := writeRegistry(registry); err != nil {
		return err
	}

	var out bytes.Buffer
	out.WriteString("# Java Edition 1.7.10 item id and damage to Bedrock item.\n")
	out.WriteString("# Generated by internal/gen from source.json; do not edit.\n")
	out.WriteString("# id\tdamage\tbedrock item\tbedrock id\tbedrock metadata\n")
	for id := legacy.MaxBlockID + 1; id <= legacy.MaxItemID; id++ {
		if !legacy.RegisteredItem(id) {
			continue
		}
		values := damages(flattening.Items, id)
		if len(values) == 0 {
			return fmt.Errorf("item %d has no flattened name", id)
		}
		for _, damage := range values {
			flattened := flattening.Items[fmt.Sprintf("%d:%d", id, damage)]
			name, metadata := bedrockItemFor(strings.TrimPrefix(flattened, "minecraft:"))
			bedrock, ok := ids[name]
			if !ok {
				return fmt.Errorf("%d:%d %s: no Bedrock item %q", id, damage, flattened, name)
			}
			fmt.Fprintf(&out, "%d\t%d\tminecraft:%s\t%d\t%d\n", id, damage, name, bedrock, metadata)
		}
	}
	return os.WriteFile("items.tsv", out.Bytes(), 0o644)
}

// damages lists the damage values the flattening table defines for a Java item id, in order.
func damages(items map[string]string, id int) []int {
	var values []int
	prefix := strconv.Itoa(id) + ":"
	for key := range items {
		if damage, ok := strings.CutPrefix(key, prefix); ok {
			if value, err := strconv.Atoi(damage); err == nil {
				values = append(values, value)
			}
		}
	}
	sort.Ints(values)
	return values
}

// bedrockItemFor names the Bedrock item and metadata for a flattened Java item name.
func bedrockItemFor(java string) (string, int) {
	if strings.HasSuffix(java, "_bed") {
		// Bedrock keeps one bed item whose metadata is its colour; 1.7.10 beds are red.
		return "bed", 14
	}
	if renamed, ok := renamedItems[java]; ok {
		return renamed, 0
	}
	return java, 0
}

// writeRegistry stores the Bedrock item registry as gzip-compressed JSON lines of
// {name, id, component flag, version, typed NBT}.
func writeRegistry(registry []bedrockItem) error {
	var raw bytes.Buffer
	zipped, err := gzip.NewWriterLevel(&raw, gzip.BestCompression)
	if err != nil {
		return err
	}
	encoder := json.NewEncoder(zipped)
	for _, item := range registry {
		entry := legacy.RegistryItem{Name: "minecraft:" + item.Name, ID: int16(item.ID), ComponentBased: item.ComponentBased, Version: item.Version, NBT: item.NBT}
		if err := encoder.Encode(entry); err != nil {
			return err
		}
	}
	if err := zipped.Close(); err != nil {
		return err
	}
	return os.WriteFile("bedrock_items.jsonl.gz", raw.Bytes(), 0o644)
}
