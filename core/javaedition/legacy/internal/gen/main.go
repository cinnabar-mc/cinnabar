// Command gen regenerates blocks.tsv, the Java Edition 1.7.10 block table, from the pinned
// PrismarineJS/minecraft-data revision recorded in source.json.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/hashimthearab/rust-mcbe/core/javaedition/legacy"
)

// source pins the upstream revision and the content hashes of the files read from it.
type source struct {
	Repository string            `json:"repository"`
	Commit     string            `json:"commit"`
	Files      map[string]string `json:"files"`
}

// javaBlock is one entry of minecraft-data's Java block list, reduced to what defaults need.
type javaBlock struct {
	Name         string `json:"name"`
	MinStateID   int    `json:"minStateId"`
	DefaultState int    `json:"defaultState"`
	States       []struct {
		Name      string   `json:"name"`
		Type      string   `json:"type"`
		NumValues int      `json:"num_values"`
		Values    []string `json:"values"`
	} `json:"states"`
}

// bedrockState is one entry of minecraft-data's Bedrock block state list.
type bedrockState struct {
	Name   string `json:"name"`
	States map[string]struct {
		Type  string `json:"type"`
		Value any    `json:"value"`
	} `json:"states"`
}

// indexStates groups the target version's block states by block name, with each property in
// its Bedrock type.
func indexStates(states []bedrockState) map[string][]legacy.State {
	index := make(map[string][]legacy.State)
	for _, entry := range states {
		state := legacy.State{Name: "minecraft:" + entry.Name, Properties: map[string]any{}}
		for key, property := range entry.States {
			switch value := property.Value.(type) {
			case string:
				state.Properties[key] = value
			case float64:
				if property.Type == "byte" {
					state.Properties[key] = value != 0
				} else {
					state.Properties[key] = int32(value)
				}
			}
		}
		index[state.Name] = append(index[state.Name], state)
	}
	return index
}

// complete returns the target version's state for a mapped state. The mapping table predates
// the target version, which added neighbour-dependent properties to some blocks; those take
// their unconnected value: false, zero or "none".
func complete(state legacy.State, registry map[string][]legacy.State) (legacy.State, error) {
	var match *legacy.State
candidates:
	for i, candidate := range registry[state.Name] {
		for key, value := range state.Properties {
			if candidate.Properties[key] != value {
				continue candidates
			}
		}
		for key, value := range candidate.Properties {
			if _, given := state.Properties[key]; given {
				continue
			}
			if value != false && value != int32(0) && value != "none" {
				continue candidates
			}
		}
		if match != nil {
			return legacy.State{}, fmt.Errorf("%s matches several states of the target version", state)
		}
		match = &registry[state.Name][i]
	}
	if match == nil {
		return legacy.State{}, fmt.Errorf("%s has no state in the target version", state)
	}
	return *match, nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

// run downloads the pinned inputs, verifies their hashes and writes blocks.tsv into the
// current directory.
func run() error {
	raw, err := os.ReadFile("source.json")
	if err != nil {
		return err
	}
	var pinned source
	if err := json.Unmarshal(raw, &pinned); err != nil {
		return fmt.Errorf("source.json: %w", err)
	}
	read := func(path string, into any) error {
		data, err := fetch(pinned, path)
		if err != nil {
			return err
		}
		return json.Unmarshal(data, into)
	}
	var flattening struct {
		Blocks map[string]string `json:"blocks"`
	}
	var javaBlocks []javaBlock
	var javaToBedrock map[string]string
	if err := read("data/pc/common/legacy.json", &flattening); err != nil {
		return err
	}
	if err := read("data/pc/1.21.11/blocks.json", &javaBlocks); err != nil {
		return err
	}
	if err := read("data/bedrock/1.26.30/blocksJ2B.json", &javaToBedrock); err != nil {
		return err
	}
	var current []bedrockState
	if err := read("data/bedrock/1.26.60/blockStates.json", &current); err != nil {
		return err
	}
	registry := indexStates(current)
	defaults := javaDefaults(javaBlocks)
	states := make(map[string]string, len(javaToBedrock))
	for java, bedrock := range javaToBedrock {
		states[canonical(java)] = bedrock
	}

	var out bytes.Buffer
	out.WriteString("# Java Edition 1.7.10 block id and metadata to Bedrock block state.\n")
	out.WriteString("# Generated by internal/gen from source.json; do not edit.\n")
	out.WriteString("# id\tmeta\tbedrock state\tnetwork hash\n")
	for id := 0; id <= legacy.MaxBlockID; id++ {
		if !legacy.Registered(id) {
			continue
		}
		for meta := 0; meta < 16; meta++ {
			flattened, ok := flattening.Blocks[fmt.Sprintf("%d:%d", id, meta)]
			if !ok {
				continue
			}
			bedrock, err := resolve(legacy.Flattened(id, meta, flattened), defaults, states)
			if err != nil {
				return fmt.Errorf("%d:%d %s: %w", id, meta, flattened, err)
			}
			state, err := legacy.ParseState(bedrock)
			if err == nil {
				state, err = complete(state, registry)
			}
			if err != nil {
				return fmt.Errorf("%d:%d %s: %w", id, meta, bedrock, err)
			}
			fmt.Fprintf(&out, "%d\t%d\t%s\t%d\n", id, meta, state.String(), state.NetworkHash())
		}
	}
	if err := os.WriteFile("blocks.tsv", out.Bytes(), 0o644); err != nil {
		return err
	}
	return writeItems(read)
}

// fetch downloads one pinned file and rejects content whose SHA-256 differs from source.json.
func fetch(pinned source, path string) ([]byte, error) {
	want, ok := pinned.Files[path]
	if !ok {
		return nil, fmt.Errorf("%s is not pinned in source.json", path)
	}
	client := http.Client{Timeout: 2 * time.Minute}
	url := fmt.Sprintf("https://raw.githubusercontent.com/%s/%s/%s", pinned.Repository, pinned.Commit, path)
	response, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, response.Status)
	}
	data, err := io.ReadAll(response.Body)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != want {
		return nil, fmt.Errorf("%s: sha256 %s, pinned %s", path, got, want)
	}
	return data, nil
}

// javaDefaults returns each Java block's default property values. State ids enumerate the
// properties with the last one varying fastest, and a Boolean's first value is true.
func javaDefaults(blocks []javaBlock) map[string]map[string]string {
	defaults := make(map[string]map[string]string, len(blocks))
	for _, block := range blocks {
		index := block.DefaultState - block.MinStateID
		properties := map[string]string{}
		for i := len(block.States) - 1; i >= 0; i-- {
			property := block.States[i]
			value := index % property.NumValues
			index /= property.NumValues
			switch {
			case len(property.Values) != 0:
				properties[property.Name] = property.Values[value]
			case property.Type == "bool":
				properties[property.Name] = strconv.FormatBool(value == 0)
			default:
				properties[property.Name] = strconv.Itoa(value)
			}
		}
		defaults["minecraft:"+block.Name] = properties
	}
	return defaults
}

// resolve converts one flattened Java state from the legacy table to its Bedrock state,
// filling properties the legacy table omits with the Java block's defaults.
func resolve(flattened string, defaults map[string]map[string]string, states map[string]string) (string, error) {
	name, properties, err := parseJava(flattened)
	if err != nil {
		return "", err
	}
	name, properties = migrate(name, properties)
	base, ok := defaults[name]
	if !ok {
		return "", fmt.Errorf("unknown Java block %s", name)
	}
	merged := make(map[string]string, len(base))
	for key, value := range base {
		merged[key] = value
	}
	for key, value := range properties {
		if _, ok := base[key]; !ok {
			return "", fmt.Errorf("unknown Java property %s on %s", key, name)
		}
		merged[key] = value
	}
	bedrock, ok := states[join(name, merged)]
	if !ok {
		return "", fmt.Errorf("no Bedrock state for %s", join(name, merged))
	}
	return bedrock, nil
}

// migrate rewrites names and properties the legacy table records in a form later Java
// versions changed.
func migrate(name string, properties map[string]string) (string, map[string]string) {
	switch name {
	case "minecraft:grass":
		name = "minecraft:short_grass"
	case "minecraft:grass_path":
		name = "minecraft:dirt_path"
	case "minecraft:sign":
		name = "minecraft:oak_sign"
	case "minecraft:wall_sign":
		name = "minecraft:oak_wall_sign"
	case "minecraft:cauldron":
		// Filled cauldrons became their own block.
		if level, ok := properties["level"]; ok && level != "0" {
			name = "minecraft:water_cauldron"
		} else {
			delete(properties, "level")
		}
	}
	if strings.HasSuffix(name, "_wall") {
		// Wall arms were Booleans before they gained a height.
		for _, side := range []string{"north", "south", "east", "west"} {
			switch properties[side] {
			case "true":
				properties[side] = "low"
			case "false":
				properties[side] = "none"
			}
		}
	}
	return name, properties
}

// parseJava splits "name[key=value,...]" into its name and properties.
func parseJava(state string) (string, map[string]string, error) {
	name, raw, bracket := strings.Cut(state, "[")
	properties := map[string]string{}
	if !bracket {
		return name, properties, nil
	}
	raw, ok := strings.CutSuffix(raw, "]")
	if !ok {
		return "", nil, fmt.Errorf("unterminated properties in %q", state)
	}
	for _, pair := range strings.Split(raw, ",") {
		if pair == "" {
			continue
		}
		key, value, ok := strings.Cut(pair, "=")
		if !ok {
			return "", nil, fmt.Errorf("invalid property %q in %q", pair, state)
		}
		properties[key] = value
	}
	return name, properties, nil
}

// canonical sorts a Java state's properties so equal states share one lookup key.
func canonical(state string) string {
	name, properties, err := parseJava(state)
	if err != nil {
		return state
	}
	return join(name, properties)
}

// join renders a Java state with its properties in key order.
func join(name string, properties map[string]string) string {
	keys := make([]string, 0, len(properties))
	for key := range properties {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	pairs := make([]string, len(keys))
	for i, key := range keys {
		pairs[i] = key + "=" + properties[key]
	}
	return name + "[" + strings.Join(pairs, ",") + "]"
}
