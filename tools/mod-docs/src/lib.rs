//! Checked, standalone Markdown documentation for the component contract.

use anyhow::{Context, Result, ensure};
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};
use wit_parser::{Docs, InterfaceId, Resolve, Type, TypeDefKind, TypeOwner};

mod limits;
mod render;
mod types;

#[cfg(test)]
mod tests;

const HEADER: &str = "<!-- Generated by cargo run --locked -p mod-docs. Do not edit. -->\n\n";
const PRIMARY_PACKAGE: &str = "extension";

const GUIDES: &[(&str, &str)] = &[
    ("Getting started", "getting-started"),
    ("How mods run", "how-mods-run"),
    ("Grants", "grants"),
    ("Settings and storage", "settings-and-storage"),
    ("Input", "input"),
    ("Presentation", "presentation"),
    ("World and player", "world-and-player"),
    ("Camera and rendering", "camera-and-rendering"),
    ("Paired mods", "paired-mods"),
    ("Packet mods", "packet-mods"),
];

const APPENDICES: &[(&str, &str)] = &[
    ("Personal client mods", "personal-mods"),
    ("Build a paired mod", "paired-mods"),
    ("Paired project reference", "paired-projects"),
    ("Terrain reads", "terrain"),
    ("World drawing helpers", "drawing-helpers"),
    ("Drawing materials", "drawing-materials"),
    ("Entity masks", "entity-masks"),
    ("Native packet frames", "native-frame"),
    ("Native packet menus", "native-menu"),
];

/// Locates the source checkout independently of the caller's working directory.
pub fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// Resolves all contract packages in the same order as the Rust guest bindings.
fn resolve(root: &Path) -> Result<Resolve> {
    let mut resolve = Resolve {
        all_features: true,
        ..Resolve::default()
    };
    for path in [
        "crates/experience-sdk/wit/client/deps/server-experience",
        "crates/experience-sdk/wit/session",
        "crates/mod-api/wit",
    ] {
        resolve
            .push_dir(root.join(path))
            .with_context(|| format!("parse {path}"))?;
    }
    Ok(resolve)
}

/// Requires useful source documentation instead of silently publishing blank API entries.
fn docs<'a>(docs: &'a Docs, context: &str) -> Result<&'a str> {
    let text = docs.contents.as_deref().unwrap_or("").trim();
    ensure!(!text.is_empty(), "missing WIT documentation: {context}");
    Ok(text)
}

/// Distinguishes an imported `use` alias from an interface's own documented types.
fn imported(resolve: &Resolve, id: wit_parser::TypeId) -> bool {
    let ty = &resolve.types[id];
    matches!(ty.kind, TypeDefKind::Type(Type::Id(target))
        if resolve.types[target].owner != ty.owner)
}

/// Builds deterministic names, qualifying dependencies to keep repeated interface names distinct.
fn interfaces(resolve: &Resolve) -> Result<BTreeMap<String, InterfaceId>> {
    let mut pages = BTreeMap::new();
    for (id, interface) in resolve.interfaces.iter() {
        let name = interface.name.as_deref().context("unnamed WIT interface")?;
        let package = &resolve.packages[interface.package.context("interface without package")?];
        let file = if package.name.name == PRIMARY_PACKAGE {
            name.to_owned()
        } else {
            format!("{}-{name}", package.name.name)
        };
        ensure!(
            !["index", "limits", "worlds"].contains(&file.as_str()),
            "reserved reference filename: {file}"
        );
        ensure!(
            pages.insert(file.clone(), id).is_none(),
            "duplicate reference filename: {file}"
        );
    }
    Ok(pages)
}

/// Renders every file before writing, so missing documentation cannot leave a partial reference.
fn pages(resolve: &Resolve) -> Result<BTreeMap<String, String>> {
    let interfaces = interfaces(resolve)?;
    let renderer = render::Renderer {
        resolve,
        interfaces: &interfaces,
    };
    let mut pages = BTreeMap::new();
    let mut index = format!(
        "{HEADER}# API reference\n\nThe pages below come from the WIT contract. Grants authorize calls; importing an interface grants nothing. See [limits](limits.md) and [worlds and callbacks](worlds.md).\n\n"
    );
    let mut summary =
        format!("{HEADER}# Summary\n\n[Introduction](introduction.md)\n\n# Guides\n\n");
    for (title, file) in GUIDES {
        summary.push_str(&format!("- [{title}](guides/{file}.md)\n"));
    }
    summary.push_str("\n# Reference\n\n- [API index](reference/index.md)\n- [Limits](reference/limits.md)\n- [Worlds and callbacks](reference/worlds.md)\n");
    for (file, id) in &interfaces {
        let title = renderer.interface_title(*id);
        index.push_str(&format!("- [{title}]({file}.md)\n"));
        summary.push_str(&format!("- [{title}](reference/{file}.md)\n"));
        pages.insert(format!("reference/{file}.md"), renderer.interface(*id)?);
    }
    summary.push_str("\n# Appendices\n\n");
    for (title, file) in APPENDICES {
        summary.push_str(&format!("- [{title}](appendix/{file}.md)\n"));
    }
    pages.insert("reference/index.md".into(), index);
    pages.insert("reference/limits.md".into(), limits::render());
    pages.insert("reference/worlds.md".into(), renderer.worlds()?);
    pages.insert("SUMMARY.md".into(), summary);
    for content in pages.values_mut() {
        content.truncate(content.trim_end().len());
        content.push('\n');
    }
    Ok(pages)
}

/// Updates generated pages or fails on missing, changed, or obsolete committed output.
pub fn generate(root: &Path, check: bool) -> Result<()> {
    let pages = pages(&resolve(root)?)?;
    sync(&root.join("docs/modding/src"), &pages, check)
}

/// Compares the entire generated file set, including references removed from the WIT contract.
fn sync(source: &Path, pages: &BTreeMap<String, String>, check: bool) -> Result<()> {
    let reference = source.join("reference");
    let mut stale = Vec::new();
    if reference.exists() {
        for entry in fs::read_dir(&reference)? {
            let path = entry?.path();
            if path.extension().is_some_and(|extension| extension == "md") {
                let relative = format!("reference/{}", path.file_name().unwrap().to_string_lossy());
                if !pages.contains_key(&relative) {
                    ensure!(
                        fs::read_to_string(&path)?
                            .replace("\r\n", "\n")
                            .starts_with(HEADER),
                        "unexpected handwritten reference: {}",
                        path.display()
                    );
                    stale.push(relative);
                    if !check {
                        fs::remove_file(path)?;
                    }
                }
            }
        }
    }
    for (relative, content) in pages {
        let path = source.join(relative);
        // A CRLF checkout (core.autocrlf on Windows) holds current pages too.
        let current = fs::read_to_string(&path).map(|text| text.replace("\r\n", "\n"));
        if current.ok().as_ref() != Some(content) {
            stale.push(relative.clone());
            if !check {
                fs::create_dir_all(path.parent().unwrap())?;
                fs::write(path, content)?;
            }
        }
    }
    ensure!(
        !check || stale.is_empty(),
        "modding reference is stale: {}. Run cargo run --locked -p mod-docs",
        stale.join(", ")
    );
    Ok(())
}

/// Escapes prose for a Markdown table without changing code examples elsewhere.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', "<br>")
}

/// Produces a stable explicit anchor independent of a renderer's heading rules.
fn anchor(name: &str) -> String {
    name.replace(['%', ':', ' ', '@', '/'], "-")
}

/// Links world-owned types to the section that declares them.
fn owner_anchor(resolve: &Resolve, owner: TypeOwner, name: &str) -> String {
    match owner {
        TypeOwner::World(id) => format!("{}-type-{}", resolve.worlds[id].name, anchor(name)),
        _ => format!("type-{}", anchor(name)),
    }
}
