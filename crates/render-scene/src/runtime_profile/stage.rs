    /// Position within [`Self::GPU`], or `None` for CPU stages.
    #[must_use]
    pub const fn gpu_index(self) -> Option<usize> {
        let index = self as usize;
        let first = Self::GpuFrame as usize;
        if index >= first {
            Some(index - first)
        } else {
            None
        }
    }

