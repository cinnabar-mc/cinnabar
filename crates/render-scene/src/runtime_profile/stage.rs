//! Stage identities shared by aggregate profiles, slow-frame reports and frame traces.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(usize)]
pub enum RuntimeStage {
    ActorSessionSetup,
    PackReload,
    WorldPoll,
    SurfacePreparation,
    RenderSubmission,
    ActorGeometrySetup,
    ActorArtworkSetup,
    ActorEquipmentSetup,
    NetworkIngestion,
    WorldStream,
    /// Summed between-frames service polls, received as a sample when the stream returns.
    WorldService,
    /// Frame-thread wait for the world-stream service to hand the stream back.
    WorldServiceReclaim,
    CaveVisibility,
    RenderQueueApplication,
    ChunkExtraction,
    GpuPreparation,
    IndirectPreparation,
    TransparentPreparation,
    TransparentWorker,
    OpaqueQueue,
    OpaqueDiagnostics,
    OpaqueBatchPlanning,
    TransparentQueue,
    AcceptanceTelemetry,
    /// Main-world wall time from frame-start timing to `Last`, including stream reclaim.
    MainFrame,
    /// `MainFrame` split by main-schedule phase, so work outside every named stage still names
    /// the phase that spent it: `PreUpdate`, the fixed-update loop, `Update`, and `PostUpdate`.
    MainPreUpdate,
    MainFixedUpdate,
    MainUpdate,
    MainPostUpdate,
    ActorPublication,
    /// Fixed-tick actor animation and Molang, inside `ActorPublication`.
    ActorAnimation,
    /// Per-frame actor presentation, culling and layers, inside `ActorPublication`.
    ActorPreparation,
    /// Bone matrices and instance arena build, inside `ActorPublication`.
    ActorRigBuild,
    UiPublication,
    UiPreparation,
    Particles,
    Audio,
    BlockEntities,
    /// Shader-pack terrain expansion planning and per-view draw lists, in the render world.
    ShaderpackGeometry,
    /// Shader-pack per-view uniform evaluation and packing for every program and draw.
    ShaderpackUniforms,
    /// Recording a view's shader-pack frame: shadow, geometry and full-screen passes.
    ShaderpackRecord,
    /// Render-world wall time for one frame, excluding the drawable-acquisition wait.
    RenderFrame,
    /// Update start, when input is sampled, to the end of that frame's render extraction.
    InputAge,
    /// Main-thread wait that delays the next input sample to its cadence slot or toward
    /// render-thread completion.
    InputPacingWait,
    /// How far past its deadline the pacing wait woke.
    FramePacingLateness,
    /// `MainUpdate` split along the client frame-set chain, each span running from its first
    /// set to the next span's: raw input and semantic sampling.
    UpdateInput,
    /// Screens claiming input, then semantic input finalization.
    UpdateUiAuthority,
    /// Local physics, camera and interaction.
    UpdateSimulation,
    /// Outgoing packets.
    UpdateNetworkSend,
    /// World publication, including `WorldStream`.
    UpdateWorld,
    /// Actor and UI preparation through publication, including their own stages.
    UpdatePresentation,
    /// Transform propagation in `PostUpdate`.
    PostTransforms,
    /// Bounds, frusta and visibility checks after transform propagation.
    PostVisibility,
    /// `RenderSubmission` split in execution order: every graph system recording its passes,
    /// up to the graph's submission. The `Node*` stages are groups of those systems; passes
    /// finished on worker tasks cost their recording here and their encoding in `EncodeFinish`.
    RenderGraph,
    /// Staged buffer upload copies.
    NodeUploads,
    NodeShadows,
    /// GPU culling and the terrain passes it draws.
    NodeCull,
    /// The main opaque pass and the terrain drawn before it.
    NodeOpaque,
    /// Sky and panorama.
    NodeSky,
    NodeTransparent,
    NodeHand,
    /// Resolve, post-processing, anti-aliasing, mod passes and upscaling.
    NodePost,
    /// World and overlay UI, nametag overlays and UI presentation.
    NodeUi,
    /// Finishing the encoders the graph's nodes recorded, including waiting for
    /// worker-finished passes.
    EncodeFinish,
    /// The rest of the graph's submission: uncovered swap-chain clears, screenshot and readback
    /// copies, and handing the command buffers to the queue.
    QueueSubmit,
    /// Presentation and screenshot collection, with any submission left to the renderer after
    /// the graph.
    SurfacePresent,
    /// First to last sampled GPU timestamp; on Metal, the graph submission's marker span.
    GpuFrame,
    GpuShadows,
    GpuOpaque,
    GpuTransparent,
    GpuUi,
    /// Owned UI passes measured only during explicit UI profiling.
    GpuUiRaster,
    GpuUiModel,
    GpuUiComposite,
    GpuUiInvert,
    /// The shared scene blur and mod-surface backdrop passes.
    GpuUiBackdrop,
    GpuHand,
    GpuPost,
    GpuTonemapping,
    GpuFxaa,
    GpuBlit,
    /// Owned GPU-cull passes, measured during per-pass profiling outside Metal.
    GpuCullEarly,
    GpuCullHiz,
    GpuCullRaster,
    GpuCullLate,
    GpuTerrainLate,
    /// Draw categories timed inside passes; only with aggregate profiling on capable adapters.
    GpuTerrainOpaque,
    GpuTerrainTransparent,
    /// Opaque draw categories measured only during explicit profiling.
    GpuTerrainSolid,
    GpuTerrainCutout,
    GpuTerrainModel,
    GpuTerrainDepthLiquid,
    GpuOpaqueOther,
    GpuActors,
    GpuParticles,
    GpuSky,
    GpuPanorama,
    /// Personal-mod post passes by execution slot, and mod world primitives.
    GpuModPass0,
    GpuModPass1,
    GpuModPass2,
    GpuModPass3,
    GpuModPass4,
    GpuModPass5,
    GpuModPass6,
    GpuModPass7,
    GpuModPrimitives,
    GpuFarTerrain,
    /// Shader-pack terrain expansion compute and vertex page growth copies.
    GpuShaderpackExpansion,
    /// Shader-pack shadow pass with its depth copies and `shadowcomp` passes.
    GpuShaderpackShadow,
    /// Shader-pack `prepare`, sky, opaque geometry, actors, effects and depth copies.
    GpuShaderpackOpaque,
    /// Shader-pack `deferred` passes.
    GpuShaderpackDeferred,
    /// Shader-pack translucent geometry, late effects and the Vanilla overlay.
    GpuShaderpackTranslucent,
    /// Shader-pack `composite`, `final`, copy-back and presentation.
    GpuShaderpackComposite,
    /// GPU time between the previous frame's last timestamp and this frame's first, when both
    /// frames were timed; untimed work between them (uploads, presentation) counts as idle.
    GpuIdle,
    /// CPU time from submission admission to its completion callback, including queue and poll delay.
    GpuFrameCompletionLatency,
}

